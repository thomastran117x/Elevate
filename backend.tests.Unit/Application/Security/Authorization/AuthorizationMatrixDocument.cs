using System.Text;

using backend.main.application.security.authorization;
using backend.tests.Unit.Support;

namespace backend.tests.Unit.Application.Security.Authorization;

/// <summary>
/// Renders the generated part of docs/AUTHORIZATION.md from the code that enforces it: the
/// permission catalog, the approved answers in <see cref="PermissionExpectations"/>, and the
/// endpoint classifications in <see cref="ApprovedPermissionMatrix"/>.
/// </summary>
public static class AuthorizationMatrixDocument
{
    public const string BeginMarker = "<!-- BEGIN GENERATED: permission matrix -->";
    public const string EndMarker = "<!-- END GENERATED: permission matrix -->";
    public const string RegenerateVariable = "UPDATE_AUTHORIZATION_DOC";

    private static readonly (Caller Caller, string Heading)[] Columns =
    [
        (Caller.Anonymous, "Anonymous"),
        (Caller.Unrelated, "Unrelated user"),
        (Caller.Member, "Member"),
        (Caller.Volunteer, "Volunteer"),
        (Caller.Manager, "Manager"),
        (Caller.Owner, "Owner"),
        (Caller.Admin, "Admin"),
        (Caller.OtherClubManager, "Other club's manager"),
        (Caller.Registrant, "Registrant"),
        (Caller.Invitee, "Invitee"),
        (Caller.Payer, "Payer"),
    ];

    public static string Render()
    {
        var builder = new StringBuilder();
        builder.AppendLine(BeginMarker);
        builder.AppendLine();
        builder.AppendLine("This section is generated by `AuthorizationMatrixDocument` in");
        builder.AppendLine("`backend.tests.Unit/Application/Security/Authorization/`. Do not edit it by hand; see");
        builder.AppendLine("[regenerating](#regenerating-the-matrix).");
        builder.AppendLine();

        RenderCatalog(builder);
        RenderAnswers(builder);
        RenderEndpoints(builder);

        builder.AppendLine(EndMarker);
        return builder.ToString().ReplaceLineEndings("\n");
    }

    private static void RenderCatalog(StringBuilder builder)
    {
        builder.AppendLine("### Permission catalog");
        builder.AppendLine();
        builder.AppendLine("| Permission | Resource | Allowed | Also allowed while the club is public | Refusal | Guards |");
        builder.AppendLine("| --- | --- | --- | --- | --- | --- |");
        foreach (var permission in Permissions.All)
        {
            builder.AppendLine(Row(
                Code(permission.Name),
                permission.Resource.ToString(),
                Relationships(permission.Allowed),
                Relationships(permission.AllowedWhenPublic),
                permission.Denial switch
                {
                    PermissionDenial.Forbid => "403",
                    PermissionDenial.Hide => "404 (hidden)",
                    PermissionDenial.ChallengeAnonymous => "401 if anonymous, else 403",
                    _ => permission.Denial.ToString(),
                },
                permission.Description));
        }

        builder.AppendLine();
    }

    private static void RenderAnswers(StringBuilder builder)
    {
        builder.AppendLine("### Approved answers by caller");
        builder.AppendLine();
        builder.AppendLine("`yes` is allowed; `401`, `403` and `404` are the refusal; `missing` is the resource's usual not-found answer.");
        builder.AppendLine();
        builder.AppendLine(Row(["Permission", "Resource", .. Columns.Select(column => column.Heading)]));
        builder.AppendLine(Row(Enumerable.Repeat("---", Columns.Length + 2).ToArray()));

        foreach (var group in PermissionExpectations.Rows.GroupBy(row => (row.Permission, row.Resource)))
        {
            var byCaller = group.ToDictionary(row => row.Caller, row => row.Expected);
            builder.AppendLine(Row(
            [
                Code(group.Key.Permission),
                group.Key.Resource,
                .. Columns.Select(column => Answer(byCaller[column.Caller])),
            ]));
        }

        builder.AppendLine();
    }

    private static void RenderEndpoints(StringBuilder builder)
    {
        builder.AppendLine("### Endpoints");
        builder.AppendLine();
        builder.AppendLine("Edge checks run in the MVC action filter or the hub filter before the action; service checks run");
        builder.AppendLine("inside the service. Every endpoint the backend declares appears here exactly once.");
        builder.AppendLine();
        builder.AppendLine("| Endpoint | Class | Edge checks | Service checks | Note |");
        builder.AppendLine("| --- | --- | --- | --- | --- |");

        foreach (var (key, entry) in ApprovedPermissionMatrix.Entries
                     .OrderBy(pair => pair.Key.Split(' ', 2)[1], StringComparer.Ordinal)
                     .ThenBy(pair => pair.Key, StringComparer.Ordinal))
        {
            builder.AppendLine(Row(
                Code(key),
                entry.Class switch
                {
                    MatrixClass.AdminPolicy => "AdminOnly policy",
                    _ => entry.Class.ToString(),
                },
                string.Join(", ", entry.EdgeChecks.Select(check => $"{Code(check.Permission)} on `{check.Parameter}`")),
                string.Join(", ", entry.ServicePermissions.Select(Code)),
                entry.Note ?? string.Empty));
        }

        builder.AppendLine();
    }

    private static string Relationships(ResourceRelationship relationships)
    {
        if (relationships == ResourceRelationship.None)
            return string.Empty;

        // Expand the ClubStaff shorthand so the table names each role.
        var names = Enum.GetValues<ResourceRelationship>()
            .Where(value => value is not (ResourceRelationship.None or ResourceRelationship.ClubStaff)
                && relationships.HasFlag(value))
            .Select(value => value.ToString());
        return string.Join(", ", names);
    }

    private static string Answer(Expect expected) => expected switch
    {
        Expect.Allow => "yes",
        Expect.Forbid => "403",
        Expect.Hide => "404",
        Expect.Challenge => "401",
        Expect.NotFound => "missing",
        _ => expected.ToString(),
    };

    private static string Code(string value) => $"`{value}`";

    private static string Row(params string[] cells) =>
        "| " + string.Join(" | ", cells.Select(cell => cell.Replace("|", "\\|", StringComparison.Ordinal))) + " |";
}
